#!/bin/bash
# Install the daily-refresh and weekly-report LaunchAgents.
#
# macOS refuses scheduled jobs read and write access to external volumes
# (kTCCServiceSystemPolicyRemovableVolumes). A job pointed straight at a script
# on this warehouse dies with exit 78 (EX_CONFIG) before it even starts, because
# launchd cannot create its own log files there.
#
# So the agents run from copies of the scripts on the internal disk and log
# there too. Only Python touches the warehouse, which it is permitted to do.
# Re-run this script after changing either script to refresh the copies.

set -euo pipefail

PROJECT_ROOT="/Volumes/Data-700GB/Basketball DS/nba_pipeline"
RUN_DIR="${HOME}/Library/Application Support/basketball-ds"
LOG_DIR="${HOME}/Library/Logs/basketball-ds"
AGENT_DIR="${HOME}/Library/LaunchAgents"
DOMAIN="gui/$(id -u)"

if [ ! -d "${PROJECT_ROOT}" ]; then
    echo "project root not available: ${PROJECT_ROOT}" >&2
    echo "mount the warehouse volume and re-run." >&2
    exit 1
fi

mkdir -p "${RUN_DIR}" "${LOG_DIR}" "${AGENT_DIR}"

# $1 label, $2 script name, $3 calendar-interval XML
write_agent() {
    local label="$1" script="$2" calendar="$3"
    local plist="${AGENT_DIR}/${label}.plist"

    install -m 755 "${PROJECT_ROOT}/scripts/${script}" "${RUN_DIR}/${script}"

    cat > "${plist}" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>${label}</string>

    <!-- Generated by scripts/install_launch_agents.sh; edit that instead.
         Paths stay on the internal disk so macOS lets launchd set the job up. -->
    <key>ProgramArguments</key>
    <array>
        <string>/bin/bash</string>
        <string>${RUN_DIR}/${script}</string>
    </array>

    <key>StartCalendarInterval</key>
    <dict>
${calendar}
    </dict>

    <key>RunAtLoad</key>
    <false/>

    <key>StandardOutPath</key>
    <string>${LOG_DIR}/${label}.out.log</string>
    <key>StandardErrorPath</key>
    <string>${LOG_DIR}/${label}.err.log</string>
</dict>
</plist>
PLIST

    launchctl bootout "${DOMAIN}/${label}" 2>/dev/null || true
    launchctl bootstrap "${DOMAIN}" "${plist}"
    echo "installed ${label}"
}

write_agent "com.basketballds.nba-refresh" "daily_refresh.sh" \
"        <key>Hour</key>
        <integer>8</integer>
        <key>Minute</key>
        <integer>0</integer>"

# Friday (weekday 5), half an hour after the daily refresh starts.
write_agent "com.basketballds.nba-weekly-report" "weekly_win_report.sh" \
"        <key>Weekday</key>
        <integer>5</integer>
        <key>Hour</key>
        <integer>8</integer>
        <key>Minute</key>
        <integer>30</integer>"

echo
echo "launchers: ${RUN_DIR}"
echo "logs:      ${LOG_DIR}"
echo
echo "Verify a job end to end with:"
echo "  launchctl kickstart -p ${DOMAIN}/com.basketballds.nba-weekly-report"
